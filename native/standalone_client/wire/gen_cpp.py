"""Emit the C++ tables for stock_wire_codec from schema.py (python3 gen_cpp.py OUTPUT)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import codec  # noqa: E402
from schema import SCHEMA  # noqa: E402

KINDS = ['u8', 'u16', 'u32', 'u64', 'i8', 'i16', 'i32', 'i64', 'f32', 'f64', 'bool', 'str', 'list',
         'map', 'tuple', 'enum', 'any', 'ref', 'oneof', 'variant']


class Tables(object):
    def __init__(self, schema):
        self.schema = schema
        self.types, self.type_index = [], {}
        self.keep = []  # id() keys stay unique only while their objects stay alive
        self.children, self.enums, self.fields, self.variants = [], [], [], []
        self.record_index = dict((name, i) for i, name in enumerate(sorted(schema.records)))
        self.records = [None] * len(self.record_index)
        for name in sorted(schema.records):
            self.records[self.record_index[name]] = self.record(schema.records[name])

    def type(self, kind):
        key = id(kind)
        if key in self.type_index:
            return self.type_index[key]
        if isinstance(kind, codec.Scalar):
            entry = (KINDS.index(kind.code), 0, 0, 0)
        elif isinstance(kind, codec.Bool):
            entry = (KINDS.index('bool'), 0, 0, 0)
        elif isinstance(kind, codec.Str):
            entry = (KINDS.index('str'), kind.maximum, 0, 0)
        elif isinstance(kind, codec.List):
            entry = (KINDS.index('list'), self.type(kind.item), kind.maximum, 0)
        elif isinstance(kind, codec.Map):
            entry = (KINDS.index('map'), self.type(kind.item), kind.maximum, 0)
        elif isinstance(kind, (codec.Tuple, codec.OneOf)):
            items = [self.type(item) for item in kind.items]
            start = len(self.children)
            self.children.extend(items)
            entry = (KINDS.index('tuple' if isinstance(kind, codec.Tuple) else 'oneof'),
                     start, len(items), 0)
        elif isinstance(kind, codec.Enum):
            start = len(self.enums)
            self.enums.extend(kind.values)
            entry = (KINDS.index('enum'), start, len(kind.values), 0)
        elif isinstance(kind, codec.Any):
            entry = (KINDS.index('any'), 0, 0, 0)
        elif isinstance(kind, codec.Ref):
            entry = (KINDS.index('ref'), self.record_index[kind.name], 0, 0)
        elif isinstance(kind, codec.Variant):
            start = len(self.variants)
            self.variants.extend((tag, self.record_index[kind.records[tag]]) for tag in kind.order)
            entry = (KINDS.index('variant'), start, len(kind.order), 0)
            self.variant_keys = getattr(self, 'variant_keys', {})
            self.variant_keys[len(self.types)] = kind.key
        else:
            raise ValueError('unsupported schema type %r' % (kind,))
        self.keep.append(kind)
        self.type_index[key] = len(self.types)
        self.types.append(entry)
        return self.type_index[key]

    def record(self, record):
        flagged = [f for f in record.fields if f.optional or f.nullable]
        first = len(self.fields)
        for f in record.fields:
            self.fields.append((f.name, None, (1 if f.optional else 0) | (2 if f.nullable else 0)))
        self.fields[first:] = [(name, self.type(f.kind), flags)
                               for (name, _, flags), f in zip(self.fields[first:], record.fields)]
        return (record.name, first, len(record.fields), len(flagged))


def cstr(value):
    return '"%s"' % value.replace('\\', '\\\\').replace('"', '\\"')


def enum_value(value):
    if value is None:
        return '{0,0,nullptr}'
    if value is False:
        return '{1,0,nullptr}'
    if value is True:
        return '{2,0,nullptr}'
    if isinstance(value, int):
        return '{3,%dLL,nullptr}' % value
    return '{4,0,%s}' % cstr(value)


def emit(schema, path):
    t = Tables(schema)
    messages = []
    for name, mid in sorted(schema.message_ids.items(), key=lambda item: item[1]):
        layout = schema.messages[name]
        if layout is None:
            messages.append((name, 0, 0, 0))
        elif isinstance(layout, tuple):
            start = len(t.children)
            t.children.extend(len(t.types) + 0 * i for i, _ in enumerate(layout))
            refs = [t.type(codec.Ref(r)) for r in layout]
            t.children[start:start + len(refs)] = refs
            messages.append((name, 2, start, len(refs)))
        else:
            messages.append((name, 1, t.record_index[layout], 0))
    keys = getattr(t, 'variant_keys', {})
    lines = ['// Generated by native/standalone_client/wire/gen_cpp.py; do not edit.',
             'static const Type types[] = {']
    for i, (kind, a, b, c) in enumerate(t.types):
        key = cstr(keys[i]) if i in keys else 'nullptr'
        lines.append('    {%d,%d,%d,%d,%s},' % (kind, a, b, c, key))
    lines += ['};', 'static const uint32_t children[] = {%s};' % ','.join(str(c) for c in (t.children or [0])),
              'static const EnumValue enums[] = {%s};' % ','.join(enum_value(v) for v in (t.enums or [None])),
              'static const FieldDesc fields[] = {']
    lines += ['    {%s,%d,%d},' % (cstr(n), ty, fl) for n, ty, fl in t.fields]
    lines += ['};', 'static const RecordDesc records[] = {']
    lines += ['    {%s,%d,%d,%d},' % (cstr(n), a, b, c) for n, a, b, c in t.records]
    lines += ['};', 'static const VariantEntry variants[] = {%s};' % ','.join(
        '{%s,%d}' % (cstr(tag), rec) for tag, rec in (t.variants or [('', 0)])),
        'static const MessageDesc messages[] = {']
    lines += ['    {%s,%d,%d,%d},' % (cstr(n), lay, a, b) for n, lay, a, b in messages]
    lines += ['};', 'static const uint32_t message_count = %d;' % len(messages), '']
    with open(path, 'w') as target:
        target.write('\n'.join(lines))


if __name__ == '__main__':
    emit(SCHEMA, sys.argv[1])
