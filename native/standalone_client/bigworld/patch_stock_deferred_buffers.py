    # named material marker operation rather than a no-op depth writer API.
    for path in (root / 'shaders').rglob('*'):
        if path.suffix not in ('.fx', '.fxh'):
            continue
        relative = path.relative_to(root).as_posix()
        if relative in pending:
            text = pending[relative]
        else:
            data = path.read_bytes()
            if (b'g_buffer_writeDepth(o, ' not in data and
                    b'g_buffer_writeObjectKind(o, g_objectID ?' not in data):
                continue
            text = data.decode('latin1')
        replaced = re.sub(r'g_buffer_writeDepth\(o, [^;]+\);',
                          'g_buffer_markLegacyMaterial(o);', text)
        # Original lightonly/normalmap COLOR shaders encode the double-sided
