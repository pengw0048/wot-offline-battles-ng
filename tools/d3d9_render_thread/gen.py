"""Generate D3D9 wrapper classes: every method defaults to a synchronous call on the render thread."""
import json, re
from pathlib import Path
HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / 'native/standalone_client/bigworld/stock_d3d9_render_thread_wrappers.inc'
I = json.load(open(HERE / 'd3d9_ifaces.json'))
WRAP = {'IDirect3DSurface9': 'WSurface', 'IDirect3DTexture9': 'WTexture', 'IDirect3DCubeTexture9': 'WCube',
        'IDirect3DVolumeTexture9': 'WVolTex', 'IDirect3DVolume9': 'WVolume', 'IDirect3DVertexBuffer9': 'WVB',
        'IDirect3DIndexBuffer9': 'WIB', 'IDirect3DVertexShader9': 'WVS', 'IDirect3DPixelShader9': 'WPS',
        'IDirect3DVertexDeclaration9': 'WDecl', 'IDirect3DStateBlock9': 'WSB', 'IDirect3DQuery9': 'WQuery',
        'IDirect3DSwapChain9': 'WSwap', 'IDirect3DBaseTexture9': 'WBaseTex'}
CLASSES = [('WDevice', 'IDirect3DDevice9Ex'), ('WSwap', 'IDirect3DSwapChain9Ex'), ('WTexture', 'IDirect3DTexture9'),
           ('WCube', 'IDirect3DCubeTexture9'), ('WVolTex', 'IDirect3DVolumeTexture9'), ('WSurface', 'IDirect3DSurface9'),
           ('WVolume', 'IDirect3DVolume9'), ('WVB', 'IDirect3DVertexBuffer9'), ('WIB', 'IDirect3DIndexBuffer9'),
           ('WVS', 'IDirect3DVertexShader9'), ('WPS', 'IDirect3DPixelShader9'), ('WDecl', 'IDirect3DVertexDeclaration9'),
           ('WSB', 'IDirect3DStateBlock9'), ('WQuery', 'IDirect3DQuery9')]
HAND = json.load(open(HERE / 'handwritten.json'))
DIRECT = {('WCube', 'GetCubeMapSurface'), ('WVolTex', 'GetVolumeLevel'), ('WVS', 'GetFunction'), ('WPS', 'GetFunction'), ('WDecl', 'GetDeclaration'), ('WDevice', 'GetAvailableTextureMem')}
def chain(i):
    out = []
    while i in I: out.append(i); i = I[i][0]
    return out
def methods(i):
    # Derived interfaces in this header redeclare inherited methods; for *Ex use base list + extras.
    base, ms = I[i]
    if i.endswith('Ex') and base in I:
        names = {m[1] for m in I[base][1]}
        return I[base][1] + [m for m in ms if m[1] not in names]
    return ms
out = ['// Generated by gen.py from mingw d3d9.h; do not edit.']
for cls, iface in CLASSES:
    out.append('struct %s final : RefBase<%s> {' % (cls, iface))
    out.append('    using RefBase<%s>::RefBase;' % iface)
    out.append('    static void* s_vtbl;')
    iids = ' || '.join('riid == __uuidof(%s)' % c for c in chain(iface) if not (c.endswith('Ex') and cls in ('WDevice', 'WSwap')))
    exc = ''
    if cls in ('WDevice', 'WSwap'):
        exc = ' || (ex && riid == __uuidof(%s))' % iface
    out.append('    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID riid, void** out) override { if (riid == __uuidof(IUnknown) || %s%s) { *out = this; AddRef(); return S_OK; } *out = nullptr; return E_NOINTERFACE; }' % (iids, exc))
    for ret, name, params in methods(iface):
        if name in ('QueryInterface', 'AddRef', 'Release'):
            continue
        decl = ', '.join('%s %s' % (t, n) for t, n in params)
        sig = '%s STDMETHODCALLTYPE %s(%s) override' % (ret, name, decl)
        if name in HAND.get(cls, []) or name in HAND.get('*', []):
            out.append('    ' + sig + ';'); continue
        conv, post = [], []
        for t, n in params:
            bt = t.replace('const', '').replace('*', '').strip()
            stars = t.count('*')
            if bt in WRAP and stars == 1:
                conv.append('rt::unwrap(%s)' % n)
            elif bt in WRAP and stars == 2:
                conv.append(n); post.append('if (%s && *%s) *%s = rt::wrapOut(self, *%s);' % (n, n, n, n))
            elif bt == 'IDirect3DDevice9' and stars == 2:
                conv.append(n); post.append('if (%s && *%s) { (*%s)->Release(); *%s = rt::device(); rt::device()->AddRef(); }' % (n, n, n, n))
            else:
                conv.append(n)
        call = 'real->%s(%s)' % (name, ', '.join(conv))
        if (cls, name) in DIRECT or (cls == 'WDevice' and name.startswith('Create') and name not in ('CreateStateBlock', 'CreateQuery')):
            # Creation and immutable queries do not depend on queued order; the MULTITHREADED
            # runtime serialises them, so they run on the caller without waiting for the queue.
            body = '%s r = %s; %s return r;' % (ret, call, ' '.join(post))
            out.append('    %s { auto* self = this; (void)self; %s }' % (sig, body))
            continue
        if ret == 'void':
            out.append('    %s { rt::sync([&]() -> int { %s; return 0; }, "%s.%s"); }' % (sig, call, cls, name))
            continue
        body = '%s r = %s; %s return r;' % (ret, call, ' '.join(post))
        out.append('    %s { auto* self = this; (void)self; return rt::sync([&]() -> %s { %s }, "%s.%s"); }' % (sig, ret, body, cls, name))
    out.append('};')
open(OUTPUT, 'w').write('\n'.join(out) + '\n')
print(sum(1 for l in out if 'STDMETHODCALLTYPE' in l), 'methods')
